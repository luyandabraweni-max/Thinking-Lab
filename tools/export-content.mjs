#!/usr/bin/env node
// Exports the live site's lessons, word help and skills tracks into the platform's content data files
// (packages/content/data). The live site stays the source until the platform replaces it; CI runs this and fails
// if the data files are out of date. Run from the repo root: node tools/export-content.mjs
import { copyFileSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { loadApp } from "../tests/unit/load-app.js";

const out = new URL("../packages/content/data/", import.meta.url);
const app = loadApp();
// Lessons for other curricula (js/content/platform/) are for the new app only: the live site doesn't load them.
// They use the live site's helpers, so they run in the same page, after its scripts.
app.run("var PLATFORM_UNITS = [];");
const extra = new URL("../js/content/platform/", import.meta.url);
for (const f of readdirSync(extra).filter(f => f.endsWith(".js")).sort()) app.window.eval(readFileSync(new URL(f, extra), "utf8"));
const { units, words, skills } = JSON.parse(app.run("JSON.stringify({ units: UNITS.concat(PLATFORM_UNITS), words: WORDS, skills: { list: SKILLS, soon: SKILLS_SOON, levels: SKILL_LEVELS, how: SKILL_HOW } })"));
const levelKey = g => (g === -1 ? "early" : g === 13 ? "adult" : `grade-${g}`);

mkdirSync(out, { recursive: true });
for (const f of readdirSync(out)) if (f.endsWith(".json")) rmSync(new URL(f, out));
const write = (name, data) => writeFileSync(new URL(name, out), JSON.stringify(data, null, 1) + "\n");

// One pack per level: the lessons and their word help.
const byLevel = new Map();
for (const u of units) { const k = levelKey(u.grade); if (!byLevel.has(k)) byLevel.set(k, []); byLevel.get(k).push(u); }
for (const [k, us] of byLevel) write(`units-${k}.json`, { level: k, units: us, words: Object.fromEntries(us.filter(u => words[u.id]).map(u => [u.id, words[u.id]])) });
// The catalogue: every lesson's summary, small enough to ship with the app.
write("catalogue.json", units.map(u => ({ id: u.id, grade: u.grade, subject: u.subject, title: u.title, topic: u.topic, domain: u.domain, category: u.category, caps: u.caps, ...(u.curriculum ? { curriculum: u.curriculum } : {}), ...(u.upTo !== undefined ? { upTo: u.upTo } : {}), pack: levelKey(u.grade) })));
write("skills.json", skills);
// The live stylesheet (games, lessons, display modes) and its fonts, for the platform's design system. Its tokens
// (lines 8 to 82) already live in packages/ui/src/tokens.css, so only the font faces and the rules after them are copied.
const css = readFileSync(new URL("../css/app.css", import.meta.url), "utf8").split("\n");
const ui = new URL("../packages/ui/src/", import.meta.url);
mkdirSync(new URL("fonts/", ui), { recursive: true });
for (const f of readdirSync(new URL("../fonts/", import.meta.url))) copyFileSync(new URL(`../fonts/${f}`, import.meta.url), new URL(`fonts/${f}`, ui));
writeFileSync(new URL("legacy.css", ui), "/* Generated by tools/export-content.mjs from css/app.css. Don't edit here: edit the live stylesheet, or move the rule into a component. */\n"
  + [...css.slice(0, 7), ...css.slice(82)].join("\n").replace(/url\("fonts\//g, 'url("./fonts/'));
console.log(`Exported ${units.length} lessons in ${byLevel.size} packs, ${Object.keys(words).length} word lists, ${skills.list.length} skills tracks.`);

// The character drawing (2to.iQ Avatar System) from js/screens/avatar.js, as a module for the app's avatar module.
// Only the option lists and the pure drawing are copied; the builder screen is written in React.
{
  const src = readFileSync(new URL("../js/screens/avatar.js", import.meta.url), "utf8");
  const cut = (from, to) => { const a = src.indexOf(from), b = src.indexOf(to, a); if (a < 0 || b < 0) throw new Error(`avatar.js changed: can't find ${from}`); return src.slice(a, b); };
  const body = cut("const AV = {", "// opts.full adds the waving arm") + cut("// Plain-language description", "// A tappable avatar");
  writeFileSync(new URL("../apps/app/src/modules/avatar/legacy-avatar.js", import.meta.url),
    "// Generated by tools/export-content.mjs from js/screens/avatar.js. Don't edit here: edit the live file.\n/* eslint-disable */\n" + body +
    "export { AV, AV_NAME_MAX, AV_SETS, AV_DRAW, avatarCode, avatarFromCode, cleanAvatarName, defaultAvatar, describeAvatar, fullAvatar };\n");
}
